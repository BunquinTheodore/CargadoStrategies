/**
 * build-kerning (DIRECTION §4.1): precomputes the display face's kerning pairs at build time,
 * so site/core/engine/kerning.js only applies a table and never measures in the browser.
 *
 *   node tools/build-kerning.mjs [--force]
 *
 * Pairs: every pair of adjacent characters inside a word of the display text in site/*.html
 * (h1-h3, and the .t-mega / .t-statement / .t-d1 / .t-d2 / .t-quote / .num-outline classes).
 * Each is measured on a canvas in headless Chrome with the display stack
 * ("Times New Roman", Times, Tinos, serif) at 100 px, upright and italic, weight 400:
 * kern = (width(ab) - width(a) - width(b)) / 100, in em; |kern| < 0.002 em is dropped.
 *
 * Output: site/assets/data/kern.json (build.mjs copies assets/data/*.json into dist):
 *   { "unit": "em", "font": "...", "pairsHash": "...", "faces": { "normal": { "Yo": -0.0712, ... }, "italic": { ... } } }
 * A face key is the CSS font-style; the weight is always 400 (Times is never bold on this site).
 *
 * The table is rebuilt only when the set of pairs changes (pairsHash) or with --force, so a
 * normal build needs no browser. Without Chrome the existing table is kept and a warning printed.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { readdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { evaluate, launchChrome } from './lib/cdp.mjs';
import { readAssembled } from './lib/assemble.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = join(ROOT, 'site');
export const KERN_FILE = join(SITE, 'assets/data/kern.json');
const FONT_STACK = '"Times New Roman", Times, Tinos, serif';
const MEASURE_PX = 100;
const MIN_KERN_EM = 0.002;
const DISPLAY = /<(h[1-3])\b[^>]*>([\s\S]*?)<\/\1>|<([a-z][a-z0-9]*)\b[^>]*class="[^"]*\b(?:t-mega|t-statement|t-d1|t-d2|t-quote|num-outline)\b[^"]*"[^>]*>([\s\S]*?)<\/\3>/gi;

const decode = (s) => s.replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;|&rsquo;/g, '’').replace(/&[a-z]+;/g, ' ');

/** The sorted list of adjacent character pairs in the site's display text. */
export async function displayPairs() {
  const files = (await readdir(SITE)).filter((f) => f.endsWith('.html'));
  const pairs = new Set();
  files.forEach((f) => {
    const html = readAssembled(join(SITE, f));
    for (const m of html.matchAll(DISPLAY)) {
      const text = decode((m[2] ?? m[4] ?? '').replace(/<[^>]+>/g, ' '));
      text.split(/\s+/).forEach((word) => {
        const ch = Array.from(word);
        for (let k = 1; k < ch.length; k++) pairs.add(ch[k - 1] + ch[k]);
      });
    }
  });
  return [...pairs].sort();
}

function measurePairs(pairs, stack, px) {
  const ctx = document.createElement('canvas').getContext('2d');
  if ('fontKerning' in ctx) ctx.fontKerning = 'normal';
  const out = {};
  ['normal', 'italic'].forEach((style) => {
    ctx.font = `${style} 400 ${px}px ${stack}`;
    const w = (t) => ctx.measureText(t).width;
    const table = {};
    pairs.forEach((p) => {
      const [a, b] = Array.from(p);
      table[p] = (w(p) - w(a) - w(b)) / px;
    });
    out[style] = table;
  });
  return out;
}

/** Rebuild kern.json when stale (or forced). Returns { status: 'fresh'|'built'|'kept', pairs, kept }. */
export async function buildKerning({ force = false } = {}) {
  const pairs = await displayPairs();
  const pairsHash = createHash('sha256').update(`${FONT_STACK}|${pairs.join('|')}`).digest('hex').slice(0, 16);
  const current = existsSync(KERN_FILE) ? JSON.parse(readFileSync(KERN_FILE, 'utf8')) : null;
  if (!force && current?.pairsHash === pairsHash) return { status: 'fresh', pairs: pairs.length, kept: Object.keys(current.faces?.normal || {}).length };
  // CI hosts (Vercel, GitHub Actions) have no Chrome: ship the committed table rather than measure.
  if (!force && current && (process.env.CI || process.env.VERCEL)) {
    return { status: 'kept', pairs: pairs.length, warning: 'CI build; kept the committed kern.json (run npm run build locally to refresh it)' };
  }
  let chrome;
  try {
    chrome = await launchChrome({ prefix: 'kern-' });
  } catch (e) {
    if (current) return { status: 'kept', pairs: pairs.length, warning: `Chrome unavailable (${e.message}); kept the existing kern.json` };
    throw e;
  }
  try {
    const raw = await evaluate(chrome.api.send, `(${measurePairs})(${JSON.stringify(pairs)}, ${JSON.stringify(FONT_STACK)}, ${MEASURE_PX})`);
    const faces = Object.fromEntries(Object.entries(raw).map(([style, table]) => [style, Object.fromEntries(
      Object.entries(table).filter(([, v]) => Math.abs(v) >= MIN_KERN_EM).map(([p, v]) => [p, Math.round(v * 10000) / 10000]),
    )]));
    const data = {
      note: 'Generated by tools/build-kerning.mjs from the display text in site/*.html. Do not edit by hand.',
      unit: 'em', font: FONT_STACK, weight: 400, measuredPx: MEASURE_PX, minEm: MIN_KERN_EM, pairsHash, pairsMeasured: pairs.length, faces,
    };
    mkdirSync(dirname(KERN_FILE), { recursive: true });
    writeFileSync(KERN_FILE, `${JSON.stringify(data, null, 1)}\n`);
    return { status: 'built', pairs: pairs.length, kept: Object.keys(faces.normal).length };
  } finally {
    await chrome.close();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildKerning({ force: process.argv.includes('--force') }).then((r) => {
    process.stdout.write(`build-kerning: ${r.status}, ${r.pairs} pairs measured, ${r.kept ?? 0} kept${r.warning ? `; ${r.warning}` : ''}\n`);
  }).catch((e) => { process.stderr.write(`build-kerning: ${e.stack || e}\n`); process.exitCode = 1; });
}
